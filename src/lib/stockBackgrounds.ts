function stockPhotoUrl(id: string, width: number): string {
  return `https://images.unsplash.com/photo-${id}?fm=jpg&q=70&w=${width}&auto=format&fit=crop`;
}

export interface StockBg {
  name: string;
  /** Full-size file used for pin rendering. */
  imageUrl: string;
  /** Small thumb for the picker grid. */
  thumbUrl: string;
}

